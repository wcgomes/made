//! Build-time index for the vendored Material Icon Theme (v5.40.0, MIT).
//!
//! This script is the only reader of `assets/material-icons/material-icons.json`.
//! It validates the mapping against the vendored `icons/` inventory, then writes
//! `explorer_icons_index.rs` into `OUT_DIR`: one `Icon` per vendored SVG,
//! embedded with `include_bytes!`, plus sorted, case-folded lookup tables.
//! Any violation fails the build, so a broken or partial vendor update cannot ship.

use std::collections::{BTreeMap, BTreeSet};
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use serde_json::{Map, Value};

/// Every upstream `iconPath` begins with this prefix.
const ICON_PATH_PREFIX: &str = "./../icons/";

/// Appended to every stray-entry error: `icons/` holds exactly the vendored SVG set.
const STRAY_ENTRY_HINT: &str = "icons/ may contain only regular .svg files, so remove it or move it out of the vendored directory";

/// OS metadata files that Finder and Explorer create in a folder. They are ignored only as
/// regular files directly in `icons/`, matched by exact, case-sensitive name.
const OS_METADATA_FILES: [&str; 2] = [".DS_Store", "Thumbs.db"];

/// Mapping tables the resolver reads. The `light`, `highContrast`,
/// `languageIds`, and `hidesExplorerArrows` sections are deliberately absent.
const FILE_TABLES: [(&str, &str); 4] = [
    ("fileNames", "FILE_NAMES"),
    ("fileExtensions", "FILE_EXTENSIONS"),
    ("folderNames", "FOLDER_NAMES"),
    ("folderNamesExpanded", "FOLDER_NAMES_EXPANDED"),
];

fn main() {
    let manifest_dir =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    let assets = manifest_dir.join("assets").join("material-icons");
    let mapping_path = assets.join("material-icons.json");
    let icons_dir = assets.join("icons");

    println!("cargo:rerun-if-changed={}", mapping_path.display());
    println!("cargo:rerun-if-changed={}", icons_dir.display());

    let index = generate(&mapping_path, &icons_dir)
        .unwrap_or_else(|error| panic!("explorer icon index: {error}"));
    let target = out_dir.join("explorer_icons_index.rs");
    fs::write(&target, index).unwrap_or_else(|error| {
        panic!(
            "explorer icon index: cannot write {}: {error}",
            target.display()
        )
    });
}

/// Case folding shared with the runtime resolver. `str::to_lowercase` does not
/// depend on the operating-system locale, so build and app agree on every key.
fn fold(key: &str) -> String {
    key.to_lowercase()
}

fn generate(mapping_path: &Path, icons_dir: &Path) -> Result<String, String> {
    let svgs = vendored_svgs(icons_dir)?;
    let mapping = read_mapping(mapping_path)?;
    let files = definition_files(&mapping, &svgs)?;

    // A complete set: every vendored SVG must be named by some definition.
    let referenced: BTreeSet<&String> = files.values().collect();
    if let Some(orphan) = svgs.iter().find(|name| !referenced.contains(name)) {
        return Err(format!(
            "vendored icon {orphan} is not referenced by any iconDefinitions entry"
        ));
    }

    let indices: BTreeMap<String, u16> = svgs
        .iter()
        .enumerate()
        .map(|(index, name)| {
            u16::try_from(index)
                .map(|index| (name.clone(), index))
                .map_err(|_| "more than 65535 icons".to_owned())
        })
        .collect::<Result<_, _>>()?;

    let mut tables = Vec::new();
    for (table, constant) in FILE_TABLES {
        tables.push((constant, lookup_table(&mapping, table, &files, &indices)?));
    }
    let file_default = default_icon(&mapping, "file", &files, &indices)?;
    let folder_default = default_icon(&mapping, "folder", &files, &indices)?;
    let folder_expanded_default = default_icon(&mapping, "folderExpanded", &files, &indices)?;

    let mut out = String::new();
    writeln!(
        out,
        "// Generated by crates/made-app/build.rs from the vendored Material Icon Theme"
    )
    .expect("write to String");
    writeln!(
        out,
        "// v5.40.0 mapping. Do not edit; change the vendored assets and rebuild."
    )
    .expect("write to String");
    writeln!(out, "\nstatic ICONS: &[Icon] = &[").expect("write to String");
    for name in &svgs {
        let uri = format!("bytes://material-icons/{name}");
        let include = format!("/assets/material-icons/icons/{name}");
        writeln!(out, "    Icon {{").expect("write to String");
        writeln!(out, "        name: {name:?},").expect("write to String");
        writeln!(out, "        uri: {uri:?},").expect("write to String");
        writeln!(
            out,
            "        bytes: include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), {include:?})),"
        )
        .expect("write to String");
        writeln!(out, "    }},").expect("write to String");
    }
    writeln!(out, "];").expect("write to String");
    for (constant, table) in &tables {
        writeln!(out, "\nstatic {constant}: &[(&str, u16)] = &[").expect("write to String");
        for (folded, index) in table {
            writeln!(out, "    ({folded:?}, {index}),").expect("write to String");
        }
        writeln!(out, "];").expect("write to String");
    }
    writeln!(out, "\nconst DEFAULT_FILE: u16 = {file_default};").expect("write to String");
    writeln!(out, "const DEFAULT_FOLDER: u16 = {folder_default};").expect("write to String");
    writeln!(
        out,
        "const DEFAULT_FOLDER_EXPANDED: u16 = {folder_expanded_default};"
    )
    .expect("write to String");
    Ok(out)
}

/// The vendored SVG inventory: every entry in `icons/`, each a regular `.svg` file.
///
/// Each file must have a plain ASCII name, be non-empty, be UTF-8, and contain
/// an `<svg` element. Any other entry, such as a stray file, a subdirectory, or
/// a symbolic link, fails the build rather than being skipped, except the exact
/// OS metadata files in `OS_METADATA_FILES`.
fn vendored_svgs(icons_dir: &Path) -> Result<BTreeSet<String>, String> {
    let read_error =
        |error: std::io::Error| format!("cannot read {}: {error}", icons_dir.display());
    let mut svgs = BTreeSet::new();
    for entry in fs::read_dir(icons_dir).map_err(read_error)? {
        let entry = entry.map_err(read_error)?;
        let name = entry.file_name().to_string_lossy().into_owned();
        let file_type = entry.file_type().map_err(read_error)?;
        if file_type.is_file() && OS_METADATA_FILES.contains(&name.as_str()) {
            continue;
        }
        if file_type.is_dir() {
            return Err(format!("icons/{name} is a directory; {STRAY_ENTRY_HINT}"));
        }
        if !file_type.is_file() {
            return Err(format!(
                "icons/{name} is not a regular file; {STRAY_ENTRY_HINT}"
            ));
        }
        if !name.ends_with(".svg") {
            return Err(format!(
                "icons/{name} is not an .svg file; {STRAY_ENTRY_HINT}"
            ));
        }
        validate_icon_name(&name)?;
        let bytes = fs::read(entry.path()).map_err(read_error)?;
        if bytes.is_empty() {
            return Err(format!("icons/{name} is empty"));
        }
        let text =
            std::str::from_utf8(&bytes).map_err(|_| format!("icons/{name} is not UTF-8 text"))?;
        if !text.contains("<svg") {
            return Err(format!("icons/{name} has no <svg> element"));
        }
        svgs.insert(name);
    }
    if svgs.is_empty() {
        return Err(format!("no SVG icons in {}", icons_dir.display()));
    }
    Ok(svgs)
}

/// Icon file names are emitted into generated Rust literals, so they must be
/// plain: ASCII letters, digits, `.`, `-`, or `_`, not hidden, ending in `.svg`.
fn validate_icon_name(name: &str) -> Result<(), String> {
    let plain = name.len() > ".svg".len()
        && !name.starts_with('.')
        && name
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'-' | b'_'));
    if plain && name.ends_with(".svg") {
        Ok(())
    } else {
        Err(format!(
            "icon file name {name:?} must be ASCII letters, digits, '.', '-', or '_' ending in .svg"
        ))
    }
}

fn read_mapping(path: &Path) -> Result<Map<String, Value>, String> {
    let bytes =
        fs::read(path).map_err(|error| format!("cannot read {}: {error}", path.display()))?;
    let value = serde_json::from_slice::<Value>(&bytes)
        .map_err(|error| format!("{} is not valid JSON: {error}", path.display()))?;
    let text = std::str::from_utf8(&bytes)
        .map_err(|error| format!("{} is not valid UTF-8: {error}", path.display()))?;
    if let Some(duplicate) = repeated_key(text) {
        return Err(format!(
            "{} is not a valid mapping: {duplicate}",
            path.display()
        ));
    }
    match value {
        Value::Object(map) => Ok(map),
        _ => Err(format!("{} must be a JSON object", path.display())),
    }
}

/// Finds the first object key that repeats within its own object, at any depth.
///
/// `serde_json` keeps only the last value of a repeated key, so a colliding
/// entry would otherwise replace an earlier one silently. This runs after the
/// mapping has parsed as JSON, so it can rely on valid syntax. Keys are decoded
/// with `serde_json`, so an escaped spelling of a key matches its plain form.
fn repeated_key(json: &str) -> Option<String> {
    let bytes = json.as_bytes();
    // One entry per open container: the keys seen so far in an object, or `None`
    // for an array.
    let mut scopes: Vec<Option<BTreeSet<String>>> = Vec::new();
    let mut expect_key = false;
    let mut index = 0;
    while index < bytes.len() {
        match bytes[index] {
            b'{' => {
                scopes.push(Some(BTreeSet::new()));
                expect_key = true;
            }
            b'[' => {
                scopes.push(None);
                expect_key = false;
            }
            b'}' | b']' => {
                scopes.pop();
                expect_key = false;
            }
            b',' => expect_key = matches!(scopes.last(), Some(Some(_))),
            b':' => expect_key = false,
            b'"' => {
                let start = index;
                index += 1;
                while index < bytes.len() && bytes[index] != b'"' {
                    index += if bytes[index] == b'\\' { 2 } else { 1 };
                }
                if expect_key {
                    if let Some(Some(keys)) = scopes.last_mut() {
                        let key: String = serde_json::from_str(json.get(start..=index)?).ok()?;
                        if !keys.insert(key.clone()) {
                            return Some(format!(
                                "duplicate object key {key:?} at {}",
                                position(json, start)
                            ));
                        }
                    }
                }
            }
            _ => {}
        }
        index += 1;
    }
    None
}

/// `line L column C` (1-based) of a byte offset in `json`.
fn position(json: &str, offset: usize) -> String {
    let before = &json[..offset];
    let line = before.matches('\n').count() + 1;
    let column = offset - before.rfind('\n').map_or(0, |newline| newline + 1) + 1;
    format!("line {line} column {column}")
}

/// Map each `iconDefinitions` key to the vendored file its `iconPath` names.
///
/// The file is taken from the path's basename, not from the definition key:
/// 72 upstream definitions name differently spelled files, such as `latex`
/// pointing at `latex.clone.svg`.
fn definition_files(
    mapping: &Map<String, Value>,
    svgs: &BTreeSet<String>,
) -> Result<BTreeMap<String, String>, String> {
    let definitions = mapping
        .get("iconDefinitions")
        .and_then(Value::as_object)
        .ok_or("iconDefinitions must be a JSON object")?;
    let mut files = BTreeMap::new();
    for (key, definition) in definitions {
        if key.trim().is_empty() {
            return Err("iconDefinitions has an empty key".to_owned());
        }
        let path = definition
            .get("iconPath")
            .and_then(Value::as_str)
            .ok_or_else(|| format!("iconDefinitions.{key} has no iconPath"))?;
        let file = icon_file(path).map_err(|reason| format!("iconDefinitions.{key}: {reason}"))?;
        if !svgs.contains(&file) {
            return Err(format!(
                "iconDefinitions.{key} references missing icon {file}"
            ));
        }
        files.insert(key.clone(), file);
    }
    Ok(files)
}

/// Normalize `./../icons/<name>.svg` to `<name>.svg`, rejecting anything that
/// could leave the vendored `icons/` directory.
fn icon_file(path: &str) -> Result<String, String> {
    let name = path
        .strip_prefix(ICON_PATH_PREFIX)
        .ok_or_else(|| format!("iconPath {path:?} is not under {ICON_PATH_PREFIX:?}"))?;
    if name.is_empty() || name.contains(['/', '\\', ':']) {
        return Err(format!(
            "iconPath {path:?} escapes the vendored icons directory"
        ));
    }
    validate_icon_name(name)?;
    Ok(name.to_owned())
}

/// Build one sorted, case-folded table from a mapping section, rejecting empty
/// keys, dangling definition keys, and keys that collide after folding.
fn lookup_table(
    mapping: &Map<String, Value>,
    table: &str,
    files: &BTreeMap<String, String>,
    indices: &BTreeMap<String, u16>,
) -> Result<Vec<(String, u16)>, String> {
    let entries = mapping
        .get(table)
        .and_then(Value::as_object)
        .ok_or_else(|| format!("{table} must be a JSON object"))?;
    let mut folded: BTreeMap<String, (String, u16)> = BTreeMap::new();
    for (key, target) in entries {
        if key.trim().is_empty() {
            return Err(format!("{table} has an empty key"));
        }
        let target = target
            .as_str()
            .ok_or_else(|| format!("{table}.{key:?} must name an iconDefinitions key"))?;
        let file = files
            .get(target)
            .ok_or_else(|| format!("{table}.{key:?} names unknown definition {target:?}"))?;
        let index = indices[file];
        if let Some((previous, _)) = folded.insert(fold(key), (key.clone(), index)) {
            return Err(format!(
                "{table} keys {previous:?} and {key:?} collide after case folding"
            ));
        }
    }
    Ok(folded
        .into_iter()
        .map(|(folded, (_, index))| (folded, index))
        .collect())
}

fn default_icon(
    mapping: &Map<String, Value>,
    key: &str,
    files: &BTreeMap<String, String>,
    indices: &BTreeMap<String, u16>,
) -> Result<u16, String> {
    let target = mapping
        .get(key)
        .and_then(Value::as_str)
        .ok_or_else(|| format!("{key} must name a default iconDefinitions key"))?;
    let file = files
        .get(target)
        .ok_or_else(|| format!("{key} names unknown definition {target:?}"))?;
    Ok(indices[file])
}
